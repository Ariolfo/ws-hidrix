    WHERE Ciu_Id IN (
        SELECT c.Ciu_Id
        FROM dbo.HidrtbCiudad c
        INNER JOIN dbo.HidrtbDepartamento d ON d.Depo_Id = c.Depo_Id
        WHERE d.Pais_Id = 170
